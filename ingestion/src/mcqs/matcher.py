"""
MCQ Matcher — Phase 1.

Joins ParsedQuestion + ParsedAnswer by question number.
Attaches the topic title from the TOC entry.
Returns a list of RawMCQ objects ready to be written to JSON.
"""

from __future__ import annotations

from typing import Optional

from src.mcqs.parser import ParsedAnswer, ParsedQuestion
from src.mcqs.schemas import RawMCQ, RawOption, Reference
from src.core.logger import logger


def match(
    questions: list[ParsedQuestion],
    answers: list[ParsedAnswer],
    unit_title: Optional[str] = None,
) -> list[RawMCQ]:
    answer_map = {a.number: a for a in answers}
    topic_name = unit_title
    matched: list[RawMCQ] = []
    matched_count = 0
    skipped_count = 0

    for q in questions:
        ans = answer_map.get(q.number)
        if ans is None:
            logger.warning(f"No answer for Q{q.number} — skipping")
            skipped_count += 1
            continue

        if not q.options:
            logger.warning(f"Q{q.number} has no options — skipping")
            skipped_count += 1
            continue

        # Check if correct answer is missing from options (e.g. F for A-E dummy options)
        correct_lbl = ans.correct_answer.upper()
        if correct_lbl not in q.options:
            # Check if these are dummy options (auto-generated by parser)
            is_dummy = any("(see " in str(v).lower() for v in q.options.values())
            if is_dummy:
                logger.info(f"Q{q.number}: Injecting missing dummy option {correct_lbl}")
                q.options[correct_lbl] = f"Option {correct_lbl} (auto-added)"

        options = [
            RawOption(label=label, text=text)  # type: ignore[arg-type]
            for label, text in sorted(q.options.items())
        ]

        # Cap at 5 options — always keep the correct answer.
        # Extended-matching questions can have up to 12 options (A–L); we
        # retain the correct one and fill the remaining 4 slots from the
        # other options in sorted label order.
        MAX_OPTIONS = 5
        if len(options) > MAX_OPTIONS:
            correct_lbl = ans.correct_answer.upper()
            correct_opt = next((o for o in options if o.label == correct_lbl), None)
            others = [o for o in options if o.label != correct_lbl]
            # Keep 4 others (sorted) + the correct one, then re-sort by label
            kept = (others[: MAX_OPTIONS - 1] + ([correct_opt] if correct_opt else []))
            options = sorted(kept, key=lambda o: o.label)
            logger.debug(
                f"Q{q.number}: trimmed {len(q.options)} -> {len(options)} options "
                f"(correct={correct_lbl} preserved)"
            )

        try:
            matched.append(RawMCQ(
                question_number=q.number,
                question_text=q.stem,
                options=options,
                correct_answer=ans.correct_answer,  # type: ignore[arg-type]
                short_explanation=ans.explanation or None,
                reference=Reference(
                    book=ans.book,
                    edition=ans.edition,
                    page=ans.page,
                ) if ans.book else None,
                see_also=ans.see_also,
                images=q.images,
                topic=topic_name,
            ))
            matched_count += 1
        except Exception as e:
            logger.error(f"Validation failed for Q{q.number}: {e}")
            skipped_count += 1
            continue

    logger.info(f"Matched {matched_count}/{len(questions)} questions ({skipped_count} skipped)")
    return matched
